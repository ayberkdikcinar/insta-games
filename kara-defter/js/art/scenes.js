// ---------- small helpers ----------
const G = (d) => `<path class="sc-ground" d="${d}"/>`;
const L = (d) => `<path class="sc-line" d="${d}"/>`;
const F = (d) => `<path class="sc-fill" d="${d}"/>`;
const SL = (d) => `<path class="sky-line" d="${d}"/>`;
const SF = (d) => `<path class="sky-fill" d="${d}"/>`;
const SM = (d) => `<path class="sky-moon" d="${d}"/>`;

// Crescent: lit side faces `dir` (1 right, -1 left); k = inner curve, closer to 1 = thinner.
function crescent(cx, cy, r, dir = 1, k = 0.6, tilt = 0) {
  const s = dir > 0 ? 1 : 0;
  return `<path class="sky-moon" transform="rotate(${tilt} ${cx} ${cy})" d="M${cx} ${cy - r} A${r} ${r} 0 0 ${s} ${cx} ${cy + r} A${(k * r).toFixed(1)} ${r} 0 0 ${1 - s} ${cx} ${cy - r} Z"/>`;
}
// Star: a small cross; `big` adds diagonals.
function star(x, y, s = 3, big = false) {
  const d = big ? ` M${x - s * 0.55} ${y - s * 0.55} L${x + s * 0.55} ${y + s * 0.55} M${x + s * 0.55} ${y - s * 0.55} L${x - s * 0.55} ${y + s * 0.55}` : '';
  return SL(`M${x - s} ${y} H${x + s} M${x} ${y - s} V${y + s}${d}`) + (big ? `<circle class="sky-moon" cx="${x}" cy="${y}" r="0.9"/>` : '');
}
const stars = (list) => list.map(([x, y, s, b]) => star(x, y, s, b)).join('');
function flake(x, y, s = 3) {
  const a = (s * 0.87).toFixed(1), h = (s / 2).toFixed(1);
  return `M${x} ${y - s} V${y + s} M${x - a} ${y - h} L${x + +a} ${y + +h} M${x - a} ${y + +h} L${x + +a} ${y - h}`;
}
function rays(cx, cy, r1, r2, n, off = 0) {
  let d = '';
  for (let i = 0; i < n; i++) {
    const t = (i / n) * Math.PI * 2 + off;
    d += `M${(cx + Math.cos(t) * r1).toFixed(1)} ${(cy + Math.sin(t) * r1).toFixed(1)} L${(cx + Math.cos(t) * r2).toFixed(1)} ${(cy + Math.sin(t) * r2).toFixed(1)} `;
  }
  return d;
}
function blossom(x, y, r = 2.4) {
  let out = '';
  for (let i = 0; i < 5; i++) {
    const t = (i / 5) * Math.PI * 2 - Math.PI / 2;
    out += `<circle class="sky-moon" cx="${(x + Math.cos(t) * r * 1.15).toFixed(1)}" cy="${(y + Math.sin(t) * r * 1.15).toFixed(1)}" r="${r}"/>`;
  }
  return out;
}

